/**
 * Regenerates the search-normalisation parity fixtures.
 *
 *   node scripts/gen-search-fixtures.mjs
 *
 * Reads `tests/fixtures/search-corpus.json` (inputs only, hand-curated) and
 * writes two generated artifacts:
 *
 *   tests/fixtures/search-golden.json      what the TypeScript side produces
 *   supabase/tests/search-normalize-parity.sql   asserts Postgres agrees
 *
 * Both are committed. `npm test` fails if either is stale, so you cannot
 * change `lib/search.ts` without regenerating -- and regenerating is what
 * reminds you to re-run the SQL half against a database.
 *
 * Why generate rather than hand-write the expectations: NFKD results are not
 * something a human should be computing in their head. The golden file records
 * what the implementation does; the SQL file checks the other implementation
 * against that same record. Neither side gets to be its own judge.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

import { normalizeSearchText, searchTokens } from "../lib/search.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export const CORPUS_PATH = join(root, "tests", "fixtures", "search-corpus.json");
export const GOLDEN_PATH = join(root, "tests", "fixtures", "search-golden.json");
export const SQL_PATH = join(root, "supabase", "tests", "search-normalize-parity.sql");

/** Every input in the corpus, in file order. */
export function readCorpus() {
  const parsed = JSON.parse(readFileSync(CORPUS_PATH, "utf8"));
  return parsed.inputs;
}

/** Run the TypeScript normalisers over the corpus. */
export function buildGolden(entries) {
  return {
    $comment: [
      "GENERATED by scripts/gen-search-fixtures.mjs -- do not edit by hand.",
      "Records what lib/search.ts produces for every corpus input.",
      "A diff here means the TypeScript normaliser changed behaviour; if that",
      "was deliberate, change public.search_normalize to match and re-run the",
      "SQL parity script before committing.",
    ],
    cases: entries.map(({ input, note }) => ({
      input,
      note,
      normalized: normalizeSearchText(input),
      tokens: searchTokens(input),
    })),
  };
}

/**
 * Postgres `E'...'` literal, ASCII-only.
 *
 * Everything outside printable ASCII becomes a `\uXXXX` escape so the .sql
 * file survives any editor, terminal or git autocrlf setting without a
 * codepoint quietly changing. That matters more than usual here: the whole
 * point of the file is comparing exact codepoints.
 */
export function sqlLiteral(value) {
  let out = "";
  for (const char of value) {
    const cp = char.codePointAt(0);
    if (char === "'") out += "\\'";
    else if (char === "\\") out += "\\\\";
    else if (cp >= 0x20 && cp <= 0x7e) out += char;
    else if (cp <= 0xffff) out += `\\u${cp.toString(16).padStart(4, "0")}`;
    else out += `\\U${cp.toString(16).padStart(8, "0")}`;
  }
  return `E'${out}'`;
}

/** A `text[]` literal built from already-escaped element literals. */
function sqlTextArray(tokens) {
  if (tokens.length === 0) return "'{}'::text[]";
  return `array[${tokens.map(sqlLiteral).join(", ")}]::text[]`;
}

export function buildSql(golden) {
  // The row separator has to come BEFORE the trailing comment, or the `--`
  // swallows the comma and the VALUES list stops parsing at row two.
  const rows = golden.cases
    .map((c, index) => {
      const comma = index === golden.cases.length - 1 ? "" : ",";
      const note = c.note ? ` -- ${c.note.replace(/\r?\n/g, " ")}` : "";
      return `    (${sqlLiteral(c.input)}, ${sqlLiteral(c.normalized)}, ${sqlTextArray(c.tokens)})${comma}${note}`;
    })
    .join("\n");

  return `-- ===========================================================================
-- GENERATED by scripts/gen-search-fixtures.mjs -- do not edit by hand.
--
-- Asserts that public.search_normalize() and public.search_tokens() agree with
-- lib/search.ts on every input in tests/fixtures/search-corpus.json.
--
-- The two implementations are hand-maintained mirrors of each other and
-- nothing in the build catches a divergence. This is that check. Run it
-- against any database that has the search migration applied:
--
--   psql "$DATABASE_URL" -f supabase/tests/search-normalize-parity.sql
--
-- Silence means parity. A divergence raises an exception listing every
-- mismatching row, so one run tells you the whole story rather than the first
-- failure only.
--
-- Expected values come from the TypeScript side (see search-golden.json).
-- Non-ASCII is \\uXXXX-escaped so the file cannot be corrupted by an editor
-- re-encoding it.
-- ===========================================================================

do $parity$
declare
  mismatches text := '';
  failed integer := 0;
  r record;
begin
  for r in
    select *
    from (values
${rows}
    ) as t(input, want_normalized, want_tokens)
  loop
    if public.search_normalize(r.input) is distinct from r.want_normalized then
      failed := failed + 1;
      mismatches := mismatches || format(
        E'\\n  search_normalize(%L)\\n    want %L\\n    got  %L',
        r.input, r.want_normalized, public.search_normalize(r.input)
      );
    end if;

    if public.search_tokens(r.input) is distinct from r.want_tokens then
      failed := failed + 1;
      mismatches := mismatches || format(
        E'\\n  search_tokens(%L)\\n    want %L\\n    got  %L',
        r.input, r.want_tokens, public.search_tokens(r.input)
      );
    end if;
  end loop;

  if failed > 0 then
    raise exception
      'search normalisation parity FAILED: % mismatch(es)%',
      failed, mismatches;
  end if;

  raise notice 'search normalisation parity OK (% cases)', ${golden.cases.length};
end
$parity$;
`;
}

/** Only write when the bytes actually change, so reruns leave mtimes alone. */
function writeIfChanged(path, contents) {
  let existing = null;
  try {
    existing = readFileSync(path, "utf8");
  } catch {
    // First run: the file does not exist yet.
  }
  if (existing === contents) return false;
  writeFileSync(path, contents, "utf8");
  return true;
}

export function generate() {
  const golden = buildGolden(readCorpus());
  const goldenJson = `${JSON.stringify(golden, null, 2)}\n`;
  const sql = buildSql(golden);
  return {
    golden,
    goldenJson,
    sql,
    wroteGolden: writeIfChanged(GOLDEN_PATH, goldenJson),
    wroteSql: writeIfChanged(SQL_PATH, sql),
  };
}

// Only generate when run directly; the test imports the builders instead.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { golden, wroteGolden, wroteSql } = generate();
  console.log(`corpus: ${golden.cases.length} cases`);
  console.log(`  ${GOLDEN_PATH}: ${wroteGolden ? "updated" : "unchanged"}`);
  console.log(`  ${SQL_PATH}: ${wroteSql ? "updated" : "unchanged"}`);
  if (wroteGolden || wroteSql) {
    console.log("\nFixtures changed. Re-run the SQL half before committing:");
    console.log('  psql "$DATABASE_URL" -f supabase/tests/search-normalize-parity.sql');
  }
}
